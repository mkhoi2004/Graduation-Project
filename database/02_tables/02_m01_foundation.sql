CREATE TABLE dbo.SchemaMigrations (
  MigrationId VARCHAR(80) NOT NULL CONSTRAINT PK_SchemaMigrations PRIMARY KEY,
  AppliedAt DATETIME2 NOT NULL CONSTRAINT DF_SchemaMigrations_AppliedAt DEFAULT SYSUTCDATETIME()
);

CREATE TABLE dbo.Roles (
  RoleId UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_Roles_Id DEFAULT NEWSEQUENTIALID(),
  Code VARCHAR(30) NOT NULL,
  Name NVARCHAR(100) NOT NULL,
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Roles_CreatedAt DEFAULT SYSUTCDATETIME(),
  CreatedBy VARCHAR(100) NOT NULL,
  Version ROWVERSION NOT NULL,
  CONSTRAINT PK_Roles PRIMARY KEY (RoleId),
  CONSTRAINT UQ_Roles_Code UNIQUE (Code),
  CONSTRAINT CK_Roles_Code CHECK (Code IN ('ADMIN','RECEPTIONIST','DOCTOR','ACCOUNTANT','WAREHOUSE'))
);

CREATE TABLE dbo.Branches (
  BranchId UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_Branches_Id DEFAULT NEWSEQUENTIALID(),
  Code VARCHAR(30) NOT NULL,
  Name NVARCHAR(200) NOT NULL,
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Branches_CreatedAt DEFAULT SYSUTCDATETIME(),
  CreatedBy VARCHAR(100) NOT NULL,
  Version ROWVERSION NOT NULL,
  CONSTRAINT PK_Branches PRIMARY KEY (BranchId),
  CONSTRAINT UQ_Branches_Code UNIQUE (Code)
);

CREATE TABLE dbo.Users (
  UserId UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_Users_Id DEFAULT NEWSEQUENTIALID(),
  Username VARCHAR(100) NOT NULL,
  DisplayName NVARCHAR(150) NOT NULL,
  PasswordHash VARCHAR(60) NOT NULL,
  RoleId UNIQUEIDENTIFIER NOT NULL,
  BranchId UNIQUEIDENTIFIER NOT NULL,
  IsApprover BIT NOT NULL CONSTRAINT DF_Users_IsApprover DEFAULT 0,
  IsActive BIT NOT NULL CONSTRAINT DF_Users_IsActive DEFAULT 1,
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Users_CreatedAt DEFAULT SYSUTCDATETIME(),
  CreatedBy VARCHAR(100) NOT NULL,
  Version ROWVERSION NOT NULL,
  CONSTRAINT PK_Users PRIMARY KEY (UserId),
  CONSTRAINT UQ_Users_Username UNIQUE (Username),
  CONSTRAINT FK_Users_Roles FOREIGN KEY (RoleId) REFERENCES dbo.Roles(RoleId),
  CONSTRAINT FK_Users_Branches FOREIGN KEY (BranchId) REFERENCES dbo.Branches(BranchId),
  CONSTRAINT CK_Users_PasswordHash CHECK (LEN(PasswordHash) = 60 AND LEFT(PasswordHash,4) IN ('$2a$','$2b$','$2y$'))
);

CREATE TABLE dbo.AccessAuditLogs (
  AuditId UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_Audit_Id DEFAULT NEWSEQUENTIALID(),
  ActorId UNIQUEIDENTIFIER NULL,
  ActorName VARCHAR(100) NOT NULL,
  RoleCode VARCHAR(30) NULL,
  Purpose NVARCHAR(300) NOT NULL,
  Action VARCHAR(50) NOT NULL,
  ObjectType VARCHAR(80) NOT NULL,
  ObjectId VARCHAR(100) NULL,
  Outcome VARCHAR(20) NOT NULL,
  Source VARCHAR(100) NOT NULL,
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Audit_CreatedAt DEFAULT SYSUTCDATETIME(),
  CONSTRAINT PK_AccessAuditLogs PRIMARY KEY (AuditId),
  CONSTRAINT CK_Audit_Outcome CHECK (Outcome IN ('ALLOWED','DENIED','FAILED'))
  -- Actor identity snapshot deliberately survives deletion of an administrative account.
);

CREATE TABLE dbo.IdempotencyKeys (
  Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_Idempotency_Id DEFAULT NEWSEQUENTIALID(),
  [Key] VARCHAR(200) COLLATE Latin1_General_100_BIN2 NOT NULL,
  Scope VARCHAR(200) COLLATE Latin1_General_100_BIN2 NOT NULL,
  RequestHash CHAR(64) NOT NULL,
  ResponseBody NVARCHAR(MAX) NOT NULL,
  ResponseStatus SMALLINT NOT NULL,
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Idempotency_CreatedAt DEFAULT SYSUTCDATETIME(),
  CONSTRAINT PK_IdempotencyKeys PRIMARY KEY (Id),
  CONSTRAINT UQ_IdempotencyKeys_Scope_Key UNIQUE (Scope, [Key]),
  CONSTRAINT CK_Idempotency_Hash CHECK (LEN(RequestHash) = 64 AND RequestHash COLLATE Latin1_General_100_BIN2 NOT LIKE '%[^0-9a-f]%'),
  CONSTRAINT CK_Idempotency_Status CHECK (ResponseStatus BETWEEN 200 AND 299),
  CONSTRAINT CK_Idempotency_Response CHECK (ISJSON(ResponseBody) = 1)
);
