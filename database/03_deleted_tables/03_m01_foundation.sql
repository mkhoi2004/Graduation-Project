CREATE TABLE dbo.Roles_Deleted (
  RoleId UNIQUEIDENTIFIER NOT NULL,
  Code VARCHAR(30) NOT NULL,
  Name NVARCHAR(100) NOT NULL,
  CreatedAt DATETIME2 NOT NULL,
  CreatedBy VARCHAR(100) NOT NULL,
  Version BINARY(8) NOT NULL,
  DeletedAt DATETIME2 NOT NULL CONSTRAINT DF_Roles_Deleted_At DEFAULT SYSUTCDATETIME(),
  DeletedBy VARCHAR(100) NOT NULL
);
CREATE INDEX IX_Roles_Deleted_Id ON dbo.Roles_Deleted(RoleId, DeletedAt);

CREATE TABLE dbo.Branches_Deleted (
  BranchId UNIQUEIDENTIFIER NOT NULL,
  Code VARCHAR(30) NOT NULL,
  Name NVARCHAR(200) NOT NULL,
  CreatedAt DATETIME2 NOT NULL,
  CreatedBy VARCHAR(100) NOT NULL,
  Version BINARY(8) NOT NULL,
  DeletedAt DATETIME2 NOT NULL CONSTRAINT DF_Branches_Deleted_At DEFAULT SYSUTCDATETIME(),
  DeletedBy VARCHAR(100) NOT NULL
);
CREATE INDEX IX_Branches_Deleted_Id ON dbo.Branches_Deleted(BranchId, DeletedAt);

CREATE TABLE dbo.Users_Deleted (
  UserId UNIQUEIDENTIFIER NOT NULL,
  Username VARCHAR(100) NOT NULL,
  DisplayName NVARCHAR(150) NOT NULL,
  PasswordHash VARCHAR(60) NOT NULL,
  RoleId UNIQUEIDENTIFIER NOT NULL,
  BranchId UNIQUEIDENTIFIER NOT NULL,
  IsApprover BIT NOT NULL,
  IsActive BIT NOT NULL,
  CreatedAt DATETIME2 NOT NULL,
  CreatedBy VARCHAR(100) NOT NULL,
  Version BINARY(8) NOT NULL,
  DeletedAt DATETIME2 NOT NULL CONSTRAINT DF_Users_Deleted_At DEFAULT SYSUTCDATETIME(),
  DeletedBy VARCHAR(100) NOT NULL
);
CREATE INDEX IX_Users_Deleted_Id ON dbo.Users_Deleted(UserId, DeletedAt);
